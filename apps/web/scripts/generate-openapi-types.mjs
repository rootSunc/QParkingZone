import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const webDir = resolve(scriptDir, '..')
const repoRoot = resolve(webDir, '..', '..')
const contractPath = resolve(repoRoot, 'docs/openapi.json')
const outputPath = resolve(webDir, 'src/api/openapi-types.ts')
const checkOnly = process.argv.includes('--check')

const contract = JSON.parse(await readFile(contractPath, 'utf8'))
const schemas = contract.components?.schemas ?? {}

function refName(ref) {
  const prefix = '#/components/schemas/'

  if (!ref?.startsWith(prefix)) {
    throw new Error(`Unsupported $ref: ${ref}`)
  }

  return ref.slice(prefix.length)
}

function typeForSchema(schema, required = true) {
  if (schema.$ref) {
    return refName(schema.$ref)
  }

  if (schema.oneOf) {
    return schema.oneOf.map((item) => typeForSchema(item)).join(' | ')
  }

  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  }

  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => typeForSchema({ ...schema, type })).join(' | ')
  }

  if (schema.type === 'array') {
    return `${typeForSchema(schema.items)}[]`
  }

  if (schema.type === 'integer' || schema.type === 'number') {
    return 'number'
  }

  if (schema.type === 'boolean') {
    return 'boolean'
  }

  if (schema.type === 'string') {
    return 'string'
  }

  if (schema.type === 'null') {
    return 'null'
  }

  if (schema.type === 'object') {
    const properties = schema.properties ?? {}
    const requiredFields = new Set(schema.required ?? [])
    const fields = Object.entries(properties).map(([name, property]) => {
      const optional = required && requiredFields.has(name) ? '' : '?'

      return `  ${name}${optional}: ${typeForSchema(property, requiredFields.has(name))}`
    })

    return `{\n${fields.join('\n')}\n}`
  }

  return 'unknown'
}

function renderSchema(name, schema) {
  if (schema.type === 'object') {
    const properties = schema.properties ?? {}
    const requiredFields = new Set(schema.required ?? [])
    const fields = Object.entries(properties).map(([propertyName, property]) => {
      const optional = requiredFields.has(propertyName) ? '' : '?'

      return `  ${propertyName}${optional}: ${typeForSchema(property, requiredFields.has(propertyName))}`
    })

    return `export interface ${name} {\n${fields.join('\n')}\n}`
  }

  return `export type ${name} = ${typeForSchema(schema)}`
}

const body = Object.entries(schemas).map(([name, schema]) => renderSchema(name, schema)).join('\n\n')
const source = `// Generated by npm run api-types:generate from docs/openapi.json.\n// Do not edit by hand.\n\n${body}\n`

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')

  if (current !== source) {
    throw new Error('Generated API types are out of date. Run npm run api-types:generate.')
  }
} else {
  await writeFile(outputPath, source)
}
